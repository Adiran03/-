#include <iostream>
using namespace std;
int main()


{
    // объявление переменных    
    double e = 0;        // требуемая точность

    // ввод
  
    cout << "Введите точность e: ";
    cin >> e;

    // если e меньше или равна 0, то программа выдает ошибку
    if (e <= 0)
    {
        cout << "Ошибка. e должен быть больше 0" << endl;
        return 1;
    }
    else
    {
        // Инициализация переменных
        double TSum = 0.967473 ;       // точное значение ряда pi^3 / 32
        int n = 0;                     // количество просуммированных элементов
        double Sum = 0;                // накопленная сумма
        int Znak = 1;                  // знак текущего слагаемого
        double Slag = 0;               // текущее слагаемое
        double Diff = 0;               // модуль разности точного значения и суммы

        while (true)
        {
            n = n + 1;

            // вычисление знаменателя (2n - 1)^3
            double base = 2 * n - 1;
            double Znam = base * base * base;

            // текущее слагаемое: (-1)^(n-1) / (2n - 1)^3
            Slag = Znak * (1 / Znam);
            Sum = Sum + Slag;

            // вычисление разности суммы и точного значения
            Diff = TSum - Sum;
            if (Diff < 0) // модуль разности
            {
                Diff = -Diff;
            }

            // условие выхода: точность достигнута
            if (Diff < e)
            {
                break;
            }

            // чередование знака для следующего элемента
            Znak = -Znak;
        }

        // Вывод результатов по условию задания
        cout << "\nВычисления успешно завершены!" << endl;
        cout << "Количество итераций (п): " << n << endl;
        cout << "Сумма ряда (Sum): " << Sum << endl;
        cout << "Точное значение (TSum): " << TSum << endl;
        cout << "Разность суммы и точного значения (Diff): " << Diff << endl;
    }

    return 0;
}


